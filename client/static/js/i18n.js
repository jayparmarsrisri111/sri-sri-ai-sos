let currentLang = localStorage.getItem('sos_lang') || 'gu';

function t(key) {
    const langDict = I18N_DATA[currentLang] || I18N_DATA['gu'];
    return langDict[key] || (I18N_DATA['en'] ? I18N_DATA['en'][key] : key) || key;
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('sos_lang', lang);

    // If native dictionary exists, apply directly
    if (I18N_DATA[lang]) {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const text = t(key);
            if (text) {
                if (el.tagName === 'INPUT' && el.type === 'button') {
                    el.value = text;
                } else {
                    el.innerText = text;
                }
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const text = t(key);
            if (text) el.placeholder = text;
        });

        if (document.title.includes("Sri Sri")) {
            document.title = `${t('appName')} - ${t('tagline')}`;
        }
    }

    // Sync all dropdowns on the page
    document.querySelectorAll('.lang-select-box').forEach(sel => {
        sel.value = lang;
    });

    // Trigger Google Translate ONLY if chosen language is not natively defined
    if (!I18N_DATA[lang]) {
        try {
            const gtSelect = document.querySelector('.goog-te-combo');
            if (gtSelect) {
                gtSelect.value = lang;
                gtSelect.dispatchEvent(new Event('change'));
            }
        } catch (e) {}
    }
    neutralizeGoogleTranslateBanner();

    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

// Voice Speech Synthesizer in current language
function speakInCurrentLanguage(text) {
    if (!('speechSynthesis' in window)) return;
    try {
        window.speechSynthesis.cancel();
        const utterance = new SpeechSynthesisUtterance(text);
        const langVoiceMap = {
            gu: 'gu-IN', hi: 'hi-IN', en: 'en-US', es: 'es-ES', fr: 'fr-FR',
            de: 'de-DE', ar: 'ar-SA', zh: 'zh-CN', ru: 'ru-RU', mr: 'mr-IN', ta: 'ta-IN'
        };
        utterance.lang = langVoiceMap[currentLang] || 'gu-IN';
        utterance.rate = 1.0;
        utterance.pitch = 1.0;
        window.speechSynthesis.speak(utterance);
    } catch (e) {
        console.warn("TTS speak failed:", e);
    }
}

// Google Translate Element Init for Universal World Support (100+ languages)
window.googleTranslateElementInit = function() {
    if (window.google && google.translate) {
        new google.translate.TranslateElement({
            pageLanguage: 'en',
            autoDisplay: false
        }, 'google_translate_element');
    }
};

function injectGoogleTranslateScript() {
    if (!document.getElementById('google-translate-script')) {
        const s = document.createElement('script');
        s.id = 'google-translate-script';
        s.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
        document.body.appendChild(s);
    }
}

// Auto-run on load
window.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('sos_lang') || 'gu';
    setLanguage(savedLang);

    // Bind all language selectors
    document.querySelectorAll('.lang-select-box').forEach(sel => {
        sel.value = currentLang;
        sel.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    });

    // Inject Google Translate script in background for all 100+ world languages
    injectGoogleTranslateScript();
});


// 🚀 PERMANENT ANTI-GOOGLE TRANSLATE BANNER NEUTRALIZER ("Google ni pati" removal)
function neutralizeGoogleTranslateBanner() {
    try {
        if (document.body && document.body.style.top && document.body.style.top !== '0px') {
            document.body.style.top = '0px';
        }
        document.querySelectorAll('.goog-te-banner-frame, iframe.goog-te-banner-frame').forEach(f => {
            f.style.setProperty('display', 'none', 'important');
            f.style.setProperty('visibility', 'hidden', 'important');
            f.style.setProperty('height', '0px', 'important');
            f.style.setProperty('width', '0px', 'important');
        });
        const gtElem = document.getElementById('google_translate_element');
        if (gtElem) gtElem.style.display = 'none';
    } catch (e) {}
}

// Watch continuously and keep body top at 0px
if (typeof window !== 'undefined') {
    const bannerObserver = new MutationObserver(() => {
        neutralizeGoogleTranslateBanner();
    });
    window.addEventListener('DOMContentLoaded', () => {
        neutralizeGoogleTranslateBanner();
        if (document.body) {
            bannerObserver.observe(document.body, { attributes: true, attributeFilter: ['style'] });
            bannerObserver.observe(document.documentElement, { childList: true, subtree: true });
        }
    });
    setInterval(neutralizeGoogleTranslateBanner, 500);
}
